// The sentinel used by the Python BLD2 writer.
static const unsigned int NO_MATERIAL = 0xFFFFFFFFu;

// Shared texture identifiers. Index equals the numeric material ID.
static std::vector<GLuint> textures;

// Terrain basename -> full BLD2 filename.
//
// This map is initialized before starting the background loader and remains
// unchanged until shutdown.
static std::map<std::string, std::string> tileFiles;

// Graphics preset rendering range, in metres.
static double maximumDistance = 1200.0;

// Atomic counter: background file failures can be displayed by the main thread.
static volatile LONG failedLoads = 0;

bool enabled = true;
unsigned long drawnBuildings = 0;
unsigned long drawnTriangles = 0;


// Read a fixed byte count.
static bool readBytes(
    std::ifstream& file,
    void* target,
    std::size_t bytes
) {
    file.read((char*)target, (std::streamsize)bytes);
    return !!file;
}


// Read one line with either Windows or Unix line endings.
static bool readLine(std::ifstream& file, std::string& line) {
    if (!std::getline(file, line)) return false;

    if (!line.empty() && line[line.size() - 1] == '\r')
        line.erase(line.size() - 1);

    return true;
}


// Read an unsigned integer from a complete metadata line.
static bool readNumber(std::ifstream& file, unsigned int& number) {
    std::string line;
    if (!readLine(file, line)) return false;

    std::istringstream input(line);
    return !!(input >> number);
}


// Convert a packaged relative path into a Windows filename.
static std::string joinPath(
    const std::string& folder,
    std::string relative
) {
    std::replace(relative.begin(), relative.end(), '/', '\\');
    return folder + "\\" + relative;
}


// Case-insensitive terrain filename key.
// No directory is included, so indexes can match a relocated terrain folder.
static std::string fileKey(const std::string& filename) {
    std::string::size_type separator = filename.find_last_of("\\/");

    std::string result = separator == std::string::npos
        ? filename : filename.substr(separator + 1);

    for (std::size_t i = 0; i < result.size(); ++i) {
        if (result[i] >= 'A' && result[i] <= 'Z')
            result[i] = (char)(result[i] - 'A' + 'a');
    }

    return result;
}


// Check existence without reading the complete file.
static bool fileExists(const std::string& filename) {
    DWORD attributes = GetFileAttributesA(filename.c_str());

    return attributes != INVALID_FILE_ATTRIBUTES
        && !(attributes & FILE_ATTRIBUTE_DIRECTORY);
}


// Validate floating-point values read from binary geometry.
static bool finiteValue(double value) {
    return value == value && value > -1e20 && value < 1e20;
}


// Load the uncompressed 32-bit bottom-origin TGA generated by Python.
// This function is called only on the main thread with a current GL context.
static GLuint loadTexture(const std::string& filename) {
    std::ifstream file(filename.c_str(), std::ios::binary);
    if (!file) return 0;

    unsigned char header[18];
    if (!readBytes(file, header, sizeof(header))) return 0;

    unsigned int width = header[12] | (header[13] << 8);
    unsigned int height = header[14] | (header[15] << 8);

    // Exact format produced by generate_building_textures.py:
    // no image ID, no palette, uncompressed true color, 32-bit BGRA,
    // bottom-left origin and eight alpha bits.
    if (header[0] != 0 || header[1] != 0 || header[2] != 2
        || header[16] != 32 || header[17] != 8
        || width == 0 || height == 0
        || width > 2048 || height > 2048) {
        return 0;
    }

    // Power-of-two textures are safest on the older hardware target.
    if ((width & (width - 1)) || (height & (height - 1)))
        return 0;

    GLint supportedSize = 0;
    glGetIntegerv(GL_MAX_TEXTURE_SIZE, &supportedSize);

    if (width > (unsigned int)supportedSize
        || height > (unsigned int)supportedSize)
        return 0;

    std::vector<unsigned char> pixels(
        (std::size_t)width * height * 4
    );

    if (!readBytes(file, &pixels[0], pixels.size())) return 0;

    // OpenGL 1.1 accepts RGBA; the TGA bytes are BGRA.
    for (std::size_t i = 0; i < pixels.size(); i += 4)
        std::swap(pixels[i], pixels[i + 2]);

    GLuint texture = 0;
    glGenTextures(1, &texture);
    if (!texture) return 0;

    glBindTexture(GL_TEXTURE_2D, texture);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);

    // Unlike vegetation sprites, building materials repeat across surfaces.
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_REPEAT);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_REPEAT);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);

    while (glGetError() != GL_NO_ERROR) {}

    glTexImage2D(
        GL_TEXTURE_2D,
        0,
        GL_RGBA,
        width,
        height,
        0,
        GL_RGBA,
        GL_UNSIGNED_BYTE,
        &pixels[0]
    );

    if (glGetError() != GL_NO_ERROR) {
        glDeleteTextures(1, &texture);
        return 0;
    }

    return texture;
}


// Initialize only the material/index entries actually supplied.
//
// A 100-building sample may occupy just a few terrain tiles. No other
// building tile files are expected or required.
bool initialize(const std::string& folder, std::string& error) {
    shutdown();
    InterlockedExchange(&failedLoads, 0);

    // Confirm the layout expected by the Python BLD2 writer.
    if (sizeof(float) != 4 || sizeof(double) != 8
        || sizeof(unsigned int) != 4 || sizeof(unsigned short) != 2
        || sizeof(Vertex) != 32) {
        error = "Unsupported compiler data layout for BLD2.";
        return false;
    }

    std::ifstream materials(
        (folder + "\\building_materials.txt").c_str()
    );

    std::string line;
    unsigned int count = 0;

    if (!readLine(materials, line)
        || line != "BUILDING_MATERIALS_V1"
        || !readNumber(materials, count)
        || count == 0 || count > 4096) {
        error = "Cannot read valid building_materials.txt.";
        return false;
    }

    textures.assign(count, 0);

    for (unsigned int i = 0; i < count; ++i) {
        unsigned int identifier;
        std::string materialName;
        std::string relative;

        if (!readNumber(materials, identifier)
            || identifier != i
            || !readLine(materials, materialName)
            || !readLine(materials, relative)) {
            error = "Invalid building material record.";
            shutdown();
            return false;
        }

        std::string filename = joinPath(folder, relative);
        textures[i] = loadTexture(filename);

        if (!textures[i]) {
            error = "Cannot load building texture:\n" + filename;
            shutdown();
            return false;
        }
    }

    std::ifstream index(
        (folder + "\\building_index.txt").c_str()
    );

    if (!readLine(index, line)
        || line != "BUILDING_INDEX_V1"
        || !readNumber(index, count)
        || count > 100000) {
        error = "Cannot read valid building_index.txt.";
        shutdown();
        return false;
    }

    for (unsigned int i = 0; i < count; ++i) {
        std::string terrainName;
        std::string relative;

        if (!readLine(index, terrainName)
            || !readLine(index, relative)) {
            error = "Truncated building_index.txt.";
            shutdown();
            return false;
        }

        std::string filename = joinPath(folder, relative);

        // Only listed existing files are mapped.
        // Terrain tiles not listed in this index simply have no buildings.
        if (!fileExists(filename)) {
            std::string warning =
                "Building file missing, skipping: " + filename + "\n";
            OutputDebugStringA(warning.c_str());
            continue;
        }

        std::string key = fileKey(terrainName);

        if (tileFiles.find(key) != tileFiles.end()) {
            error = "Duplicate terrain entry in building_index.txt:\n"
                + terrainName;
            shutdown();
            return false;
        }

        tileFiles[key] = filename;
    }

    glBindTexture(GL_TEXTURE_2D, 0);
    return true;
}


std::string filenameForTerrain(const std::string& terrainFilename) {
    std::map<std::string, std::string>::const_iterator found =
        tileFiles.find(fileKey(terrainFilename));

    return found == tileFiles.end() ? "" : found->second;
}


std::size_t Data::bytes() const {
    std::size_t total = sizeof(Data)
        + items.capacity() * sizeof(Building);

    for (std::size_t i = 0; i < items.size(); ++i) {
        total += items[i].id.capacity();
        total += items[i].groups.capacity() * sizeof(Group);

        for (std::size_t j = 0; j < items[i].groups.size(); ++j)
            total += items[i].groups[j].vertices.capacity()
                * sizeof(Vertex);
    }

    return total;
}


// Read/validate one BLD2 file. No OpenGL operations happen here.
static bool readData(
    std::ifstream& file,
    Data& data,
    bool (*cancelled)()
) {
    char magic[4];
    unsigned int buildingCount;

    if (!readBytes(file, magic, 4)
        || std::memcmp(magic, "BLD2", 4) != 0
        || !readBytes(file, &buildingCount, 4)
        || buildingCount > 100000)
        return false;

    // Limit total vertex storage per file to protect the 32-bit process.
    const std::size_t maximumVertices = 4000000;
    std::size_t totalVertices = 0;

    for (unsigned int i = 0; i < buildingCount; ++i) {
        if (cancelled()) return false;

        Building building;
        unsigned short idLength;
        unsigned int groupCount;

        if (!readBytes(file, &idLength, 2) || idLength == 0)
            return false;

        building.id.resize(idLength);
        if (!readBytes(file, &building.id[0], idLength))
            return false;

        if (!readBytes(file, &building.easting, 8)
            || !readBytes(file, &building.northing, 8)
            || !readBytes(file, &building.elevation, 8)
            || !readBytes(file, building.minimum, 12)
            || !readBytes(file, building.maximum, 12)
            || !readBytes(file, &groupCount, 4)
            || groupCount > 4096)
            return false;

        if (!finiteValue(building.easting)
            || !finiteValue(building.northing)
            || !finiteValue(building.elevation))
            return false;

        for (int axis = 0; axis < 3; ++axis) {
            if (!finiteValue(building.minimum[axis])
                || !finiteValue(building.maximum[axis])
                || building.minimum[axis] > building.maximum[axis])
                return false;
        }

        for (unsigned int j = 0; j < groupCount; ++j) {
            if (cancelled()) return false;

            Group group;
            unsigned int vertexCount;

            if (!readBytes(file, &group.category, 4)
                || !readBytes(file, &group.material, 4)
                || !readBytes(file, &vertexCount, 4)
                || vertexCount % 3 != 0)
                return false;

            if (group.material != NO_MATERIAL
                && group.material >= textures.size())
                return false;

            if (vertexCount > maximumVertices - totalVertices)
                return false;

            totalVertices += vertexCount;
            group.vertices.resize(vertexCount);

            // Read in moderate blocks, with cancellation between blocks.
            for (unsigned int start = 0; start < vertexCount; ) {
                if (cancelled()) return false;

                unsigned int block = std::min(
                    4096u, vertexCount - start
                );

                if (!readBytes(
                    file,
                    &group.vertices[start],
                    (std::size_t)block * sizeof(Vertex)
                )) {
                    return false;
                }

                for (unsigned int k = start; k < start + block; ++k) {
                    const Vertex& v = group.vertices[k];

                    if (!finiteValue(v.x) || !finiteValue(v.y)
                        || !finiteValue(v.z)
                        || !finiteValue(v.nx) || !finiteValue(v.ny)
                        || !finiteValue(v.nz)
                        || !finiteValue(v.u) || !finiteValue(v.v))
                        return false;
                }

                start += block;
            }

            // C++98 swap avoids copying the complete vertex array.
            building.groups.push_back(Group());
            Group& destination = building.groups.back();
            destination.category = group.category;
            destination.material = group.material;
            destination.vertices.swap(group.vertices);
        }

        data.items.push_back(Building());
        Building& destination = data.items.back();

        destination.id.swap(building.id);
        destination.easting = building.easting;
        destination.northing = building.northing;
        destination.elevation = building.elevation;

        std::memcpy(
            destination.minimum, building.minimum,
            sizeof(building.minimum)
        );
        std::memcpy(
            destination.maximum, building.maximum,
            sizeof(building.maximum)
        );

        destination.groups.swap(building.groups);
    }

    return !cancelled();
}


Data* load(const std::string& filename, bool (*cancelled)()) {
    // No mapping is normal for the partial 100-building dataset.
    if (filename.empty() || cancelled()) return 0;

    Data* data = new Data;

    try {
        std::ifstream file(filename.c_str(), std::ios::binary);

        if (file && readData(file, *data, cancelled()))
            return data;

    } catch (...) {
        // Allocation/read exceptions become a reported load failure.
    }

    delete data;

    if (!cancelled()) {
        InterlockedIncrement(&failedLoads);
        std::string warning = "Cannot load BLD2: " + filename + "\n";
        OutputDebugStringA(warning.c_str());
    }

    return 0;
}


void setPreset(int preset) {
    if (preset == 0)
        maximumDistance = 800;
    else if (preset == 1)
        maximumDistance = 1200;
    else
        maximumDistance = 10000;
}


void beginFrame() {
    drawnBuildings = 0;
    drawnTriangles = 0;
}


// Reject a full building bounding box only if it is outside a view plane.
static bool visibleBox(
    const double minimum[3],
    const double maximum[3],
    const double planes[6][4]
) {
    for (int p = 0; p < 6; ++p) {
        double x = planes[p][0] >= 0 ? maximum[0] : minimum[0];
        double y = planes[p][1] >= 0 ? maximum[1] : minimum[1];
        double z = planes[p][2] >= 0 ? maximum[2] : minimum[2];

        if (planes[p][0] * x
            + planes[p][1] * y
            + planes[p][2] * z
            + planes[p][3] < 0)
            return false;
    }

    return true;
}


// Distance from camera origin to a camera-relative AABB.
static double boxDistanceSquared(
    const double minimum[3],
    const double maximum[3]
) {
    double result = 0;

    for (int axis = 0; axis < 3; ++axis) {
        double distance = std::max(
            minimum[axis],
            std::max(0.0, -maximum[axis])
        );
        result += distance * distance;
    }

    return result;
}


// Draw resident geometry using the existing fixed-function lighting.
// Full building bounds are used, even across owner-tile boundaries.
void render(
    const Data* data,
    double cameraX, double cameraY, double cameraZ,
    double originX, double originY, double originZ,
    const double planes[6][4],
    bool wireframe
) {
    if (!enabled || !data) return;

    glPushAttrib(
        GL_ENABLE_BIT | GL_TEXTURE_BIT | GL_COLOR_BUFFER_BIT
        | GL_DEPTH_BUFFER_BIT | GL_POLYGON_BIT | GL_CURRENT_BIT
        | GL_LIGHTING_BIT
    );
    glPushClientAttrib(GL_CLIENT_VERTEX_ARRAY_BIT);

    glDisable(GL_BLEND);
    glDisable(GL_ALPHA_TEST);

    glEnable(GL_DEPTH_TEST);
    glDepthMask(GL_TRUE);

    glEnable(GL_LIGHTING);
    glEnable(GL_LIGHT0);
    glEnable(GL_NORMALIZE);
    glEnable(GL_COLOR_MATERIAL);
    glColorMaterial(GL_FRONT_AND_BACK, GL_AMBIENT_AND_DIFFUSE);

    // Double-sided rendering matches the inspection GLB materials.
    // This also avoids hiding thin roof overhangs when viewed from below.
    glDisable(GL_CULL_FACE);

    glPolygonMode(
        GL_FRONT_AND_BACK,
        wireframe ? GL_LINE : GL_FILL
    );

    glTexEnvi(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_MODULATE);

    glDisableClientState(GL_COLOR_ARRAY);
    glEnableClientState(GL_VERTEX_ARRAY);
    glEnableClientState(GL_NORMAL_ARRAY);
    glEnableClientState(GL_TEXTURE_COORD_ARRAY);

    const double rangeSquared = maximumDistance * maximumDistance;

    for (std::size_t i = 0; i < data->items.size(); ++i) {
        const Building& building = data->items[i];

        double translation[3] = {
            building.easting - originX - cameraX,
            building.elevation - originZ - cameraY,
            originY - building.northing - cameraZ
        };

        double minimum[3], maximum[3];

        for (int axis = 0; axis < 3; ++axis) {
            minimum[axis] = translation[axis] + building.minimum[axis];
            maximum[axis] = translation[axis] + building.maximum[axis];
        }

        if (!visibleBox(minimum, maximum, planes))
            continue;

        if (boxDistanceSquared(minimum, maximum) > rangeSquared)
            continue;

        glPushMatrix();
        glTranslated(
            translation[0], translation[1], translation[2]
        );

        bool rendered = false;

        for (std::size_t j = 0; j < building.groups.size(); ++j) {
            const Group& group = building.groups[j];
            if (group.vertices.empty()) continue;

            if (group.material == NO_MATERIAL) {
                glDisable(GL_TEXTURE_2D);
                glColor3f(0.45f, 0.43f, 0.40f);
            } else {
                glEnable(GL_TEXTURE_2D);
                glBindTexture(
                    GL_TEXTURE_2D, textures[group.material]
                );
                glColor3f(1, 1, 1);
            }

            const Vertex* vertices = &group.vertices[0];

            glVertexPointer(
                3, GL_FLOAT, sizeof(Vertex), &vertices[0].x
            );
            glNormalPointer(
                GL_FLOAT, sizeof(Vertex), &vertices[0].nx
            );
            glTexCoordPointer(
                2, GL_FLOAT, sizeof(Vertex), &vertices[0].u
            );

            glDrawArrays(
                GL_TRIANGLES,
                0,
                (GLsizei)group.vertices.size()
            );

            drawnTriangles +=
                (unsigned long)(group.vertices.size() / 3);
            rendered = true;
        }

        glPopMatrix();

        if (rendered) ++drawnBuildings;
    }

    glPopClientAttrib();
    glPopAttrib();
}


unsigned int indexedTileCount() {
    return (unsigned int)tileFiles.size();
}


long failedLoadCount() {
    return (long)InterlockedCompareExchange(&failedLoads, 0, 0);
}


void shutdown() {
    for (std::size_t i = 0; i < textures.size(); ++i)
        if (textures[i])
            glDeleteTextures(1, &textures[i]);

    textures.clear();
    tileFiles.clear();
}

