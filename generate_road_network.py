def write_road_file(path, roads):
    """Write one ROAD1 tile file."""
    with path.open("wb") as handle:
        handle.write(b"ROAD1")
        handle.write(struct.pack("<I", len(roads)))

        for road in roads:
            identifier = road["id"].encode("utf-8")
            if len(identifier) > 65535:
                raise ValueError("Road ID is too long.")

            all_positions = np.concatenate([
                group["vertices"][:, :3]
                for group in road["groups"]
            ])
            minimum = all_positions.min(axis=0)
            maximum = all_positions.max(axis=0)

            handle.write(struct.pack("<H", len(identifier)))
            handle.write(identifier)
            handle.write(struct.pack("<3d", *road["origin"]))
            handle.write(struct.pack("<6f", *minimum, *maximum))
            handle.write(struct.pack("<i", road["luokka"]))
            handle.write(struct.pack("<i", road["versuh"]))
            handle.write(struct.pack("<I", len(road["groups"])))

            for group in road["groups"]:
                vertices = group["vertices"]
                handle.write(struct.pack(
                    "<3I",
                    group["category"],
                    group["material_id"],
                    len(vertices),
                ))
                handle.write(vertices.astype("<f4").tobytes())


def write_glb(path, tile, roads, materials):
    """Write one textured inspection GLB for a viewer terrain tile."""
    scene = trimesh.Scene()

    tile_origin_x = tile["xmin"]
    tile_origin_y = tile["ymax"]

    for road in roads:
        origin = road["origin"]
        translation = np.array([
            origin[0] - tile_origin_x,
            origin[2],
            tile_origin_y - origin[1],
        ])

        for group_number, group in enumerate(road["groups"]):
            data = group["vertices"]

            mesh = trimesh.Trimesh(
                vertices=data[:, :3].astype(float) + translation,
                faces=np.arange(len(data)).reshape(-1, 3),
                vertex_normals=data[:, 3:6].astype(float),
                process=False,
            )

            name = group["material_name"]

            if name is not None:
                mesh.visual = TextureVisuals(
                    uv=data[:, 6:8],
                    material=PBRMaterial(
                        name=name,
                        baseColorTexture=materials.image(name),
                        baseColorFactor=[1.0, 1.0, 1.0, 1.0],
                        metallicFactor=0.0,
                        roughnessFactor=0.95,
                        doubleSided=True,
                    ),
                )
            else:
                mesh.visual.face_colors = [120, 115, 105, 255]

            geometry_name = f"{road['id']}_{group_number}"
            scene.add_geometry(
                mesh,
                node_name=geometry_name,
                geom_name=geometry_name,
            )

    path.write_bytes(scene.export(file_type="glb"))


def write_format_documentation(output):
    (output / "ROAD_FORMAT.txt").write_text(
        """ROAD1 binary format, little endian

Header:
  char[4]  magic: ROAD1
  uint32   road count

Per road:
  uint16   UTF-8 ID byte length
  byte[]   road ID
  float64  origin easting
  float64  origin northing
  float64  origin elevation
  float32  local minimum X,Y,Z
  float32  local maximum X,Y,Z
  int32    LUOKKA
  int32    VERSUH
  uint32   group count

Per group:
  uint32   category:
             1 road surface
             2 shoulder
  uint32   material ID
  uint32   vertex count, divisible by 3

Per vertex:
  float32 local X,Y,Z
  float32 normal X,Y,Z
  float32 U,V

Local axes:
  X east, Y up, Z south

Absolute placement:
  X = origin easting - viewerOriginX + local X
  Y = origin elevation - viewerOriginZ + local Y
  Z = viewerOriginY - origin northing + local Z

Textures use GL_REPEAT.
Roads are split by viewer terrain tile.
""",
        encoding="utf-8",
    )


