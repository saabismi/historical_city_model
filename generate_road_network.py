def class_settings(luokka):
    """Return editable class settings with fallback."""
    entry = CONFIG["classes"].get(luokka)
    if entry is None:
        entry = CONFIG["classes"]["fallback"]
        z_offset = CONFIG["class_z_offsets_metres"]["fallback"]
    else:
        z_offset = CONFIG["class_z_offsets_metres"].get(
            luokka,
            CONFIG["class_z_offsets_metres"]["fallback"],
        )

    result = dict(entry)
    result["z_offset"] = z_offset
    return result


def line_segments(line, spacing):
    """Sample a line at regular spacing, always including both endpoints."""
    length = line.length
    if length <= 0:
        return [np.asarray(line.coords[0], dtype=float)]

    distances = [0.0]
    current = spacing

    while current < length:
        distances.append(current)
        current += spacing

    distances.append(length)

    return [
        np.asarray(line.interpolate(distance).coords[0], dtype=float)
        for distance in distances
    ]


def tangent(points, index):
    """Estimate a tangent from neighboring sampled points."""
    if index == 0:
        vector = points[1] - points[0]
    elif index == len(points) - 1:
        vector = points[-1] - points[-2]
    else:
        vector = points[index + 1] - points[index - 1]

    length = np.linalg.norm(vector)
    if length < 1e-12:
        return np.array([1.0, 0.0])

    return vector / length


def side_vector(direction):
    """Right-side XY vector from the tangent direction."""
    return np.array([direction[1], -direction[0]])


def road_cross_section(settings):
    """
    Cross-section points from left outer shoulder to right outer shoulder.

    Width excludes shoulder; shoulder adds the sloped terrain join.
    """
    half_surface = settings["width"] / 2.0
    shoulder = settings["shoulder"]

    return [
        (-half_surface - shoulder, settings["outer_raise"], ROAD_SHOULDER),
        (-half_surface, settings["edge_raise"], ROAD_SURFACE),
        (0.0, settings["center_raise"], ROAD_SURFACE),
        (half_surface, settings["edge_raise"], ROAD_SURFACE),
        (half_surface + shoulder, settings["outer_raise"], ROAD_SHOULDER),
    ]


def split_at_tile(line, tile_box):
    """Clip one line to a tile rectangle and return line parts inside it."""
    clipped = line.intersection(tile_box)

    if clipped.is_empty:
        return []

    if isinstance(clipped, LineString):
        return [clipped]

    if isinstance(clipped, MultiLineString):
        return [part for part in clipped.geoms if part.length > 0]

    return []


def packed_vertices(xyz, uv, origin):
    """
    Pack local XYZ, flat normals, and UVs for ROAD1.

    Local axes:
      X east
      Y up
      Z south
    """
    xyz = np.asarray(xyz, dtype=np.float64).reshape(-1, 3)
    uv = np.asarray(uv, dtype=np.float64).reshape(-1, 2)

    if len(xyz) != len(uv) or len(xyz) % 3:
        raise ValueError("Invalid road triangle/UV data.")

    local = np.column_stack((
        xyz[:, 0] - origin[0],
        xyz[:, 2] - origin[2],
        origin[1] - xyz[:, 1],
    ))

    triangles = local.reshape(-1, 3, 3)
    normals = np.cross(
        triangles[:, 1] - triangles[:, 0],
        triangles[:, 2] - triangles[:, 0],
    )
    lengths = np.linalg.norm(normals, axis=1)

    valid = lengths > 1e-10
    triangles = triangles[valid]
    triangle_uv = uv.reshape(-1, 3, 2)[valid]
    normals = normals[valid] / lengths[valid, None]

    return np.column_stack((
        triangles.reshape(-1, 3),
        np.repeat(normals, 3, axis=0),
        triangle_uv.reshape(-1, 2),
    )).astype(np.float32)


def make_road_mesh(line, dem_sampler, settings, material_id, material):
    """
    Build one road ribbon mesh from a clipped line segment.

    Geometry is created in absolute EPSG:3067 coordinates first, then later
    converted to local viewer coordinates.
    """
    sampled = line_segments(line, CONFIG["segment_length_metres"])

    if len(sampled) < 2:
        return None

    cross = road_cross_section(settings)
    profiles = []
    chainage = [0.0]

    for index in range(1, len(sampled)):
        chainage.append(
            chainage[-1] + np.linalg.norm(sampled[index] - sampled[index - 1])
        )

    for index, point in enumerate(sampled):
        direction = tangent(sampled, index)
        side = side_vector(direction)

        profile = []
        missing = False

        for offset, raise_metres, category in cross:
            xy = point + side * offset
            z = dem_sampler.sample(float(xy[0]), float(xy[1]))

            if z is None:
                missing = True
                break

            z += raise_metres + settings["z_offset"]

            profile.append({
                "xy": xy,
                "z": z,
                "category": category,
            })

        if missing:
            profiles.append(None)
        else:
            profiles.append(profile)

    surface_xyz = []
    surface_uv = []
    shoulder_xyz = []
    shoulder_uv = []

    for index in range(len(sampled) - 1):
        first = profiles[index]
        second = profiles[index + 1]

        if first is None or second is None:
            continue

        u0 = chainage[index] / material["repeat_length_metres"]
        u1 = chainage[index + 1] / material["repeat_length_metres"]

        for lane in range(len(cross) - 1):
            left0 = first[lane]
            right0 = first[lane + 1]
            left1 = second[lane]
            right1 = second[lane + 1]

            category = max(left0["category"], right0["category"])

            xyz = np.asarray([
                [left0["xy"][0], left0["xy"][1], left0["z"]],
                [left1["xy"][0], left1["xy"][1], left1["z"]],
                [right1["xy"][0], right1["xy"][1], right1["z"]],
                [left0["xy"][0], left0["xy"][1], left0["z"]],
                [right1["xy"][0], right1["xy"][1], right1["z"]],
                [right0["xy"][0], right0["xy"][1], right0["z"]],
            ], dtype=np.float64)

            v_left = (
                cross[lane][0] - cross[0][0]
            ) / material["repeat_width_metres"]
            v_right = (
                cross[lane + 1][0] - cross[0][0]
            ) / material["repeat_width_metres"]

            uv = np.asarray([
                [u0, v_left],
                [u1, v_left],
                [u1, v_right],
                [u0, v_left],
                [u1, v_right],
                [u0, v_right],
            ], dtype=np.float64)

            if category == ROAD_SURFACE:
                surface_xyz.append(xyz)
                surface_uv.append(uv)
            else:
                shoulder_xyz.append(xyz)
                shoulder_uv.append(uv)

    if not surface_xyz and not shoulder_xyz:
        return None

    return {
        "surface_xyz": (
            np.concatenate(surface_xyz)
            if surface_xyz else np.empty((0, 3), dtype=np.float64)
        ),
        "surface_uv": (
            np.concatenate(surface_uv)
            if surface_uv else np.empty((0, 2), dtype=np.float64)
        ),
        "shoulder_xyz": (
            np.concatenate(shoulder_xyz)
            if shoulder_xyz else np.empty((0, 3), dtype=np.float64)
        ),
        "shoulder_uv": (
            np.concatenate(shoulder_uv)
            if shoulder_uv else np.empty((0, 2), dtype=np.float64)
        ),
        "material_name": settings["surface_material"],
        "material_id": material_id,
    }


