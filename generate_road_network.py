def main():
    parser = argparse.ArgumentParser(
        description="Generate a simple 3D road network from MTK tieviiva.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--roads", required=True)
    parser.add_argument("--layer", default="tieviiva")
    parser.add_argument("--dem", required=True)
    parser.add_argument("--viewer-terrain", required=True)
    parser.add_argument("--materials", required=True)
    parser.add_argument("-o", "--output", required=True)
    parser.add_argument("--glb", action="store_true")
    args = parser.parse_args()

    roads_path = Path(args.roads).resolve()
    dem_folder = Path(args.dem).resolve()
    viewer_terrain = Path(args.viewer_terrain).resolve()
    output = Path(args.output).resolve()

    if not roads_path.is_file():
        parser.error(f"Road GeoPackage does not exist: {roads_path}")
    if not (dem_folder / "tile_manifest.json").is_file():
        parser.error(
            f"DEM folder does not contain tile_manifest.json: {dem_folder}"
        )
    if not (viewer_terrain / "terrain_index.txt").is_file():
        parser.error(
            f"Viewer terrain folder does not contain terrain_index.txt: "
            f"{viewer_terrain}"
        )
    if not Path(args.materials).is_file():
        parser.error(f"Materials file does not exist: {args.materials}")

    if output.exists() and (
        not output.is_dir() or any(output.iterdir())
    ):
        parser.error("Output folder must be empty or not yet exist.")

    terrain_origin, terrain_tiles = read_viewer_terrain_index(viewer_terrain)
    dem_entries = read_dem_manifest(dem_folder)
    dem_lookup = build_dem_lookup(dem_entries, terrain_tiles)
    materials = RoadMaterials(Path(args.materials))
    roads = read_roads(roads_path, args.layer)

    output.mkdir(parents=True, exist_ok=True)
    (output / "tiles").mkdir()
    if args.glb:
        (output / "glb").mkdir()

    materials.export(output)

    grouped = defaultdict(list)
    report = []

    with DemSampler(dem_lookup, terrain_tiles) as sampler:
        for road_number, road in enumerate(roads, 1):
            print(
                f"[{road_number}/{len(roads)}] {road['id']} "
                f"(LUOKKA={road['luokka']}, VERSUH={road['versuh']})"
            )

            settings = class_settings(road["luokka"])
            material_name = settings["surface_material"]
            material_id = materials.ids[material_name]
            material = materials.table[material_name]

            for tile in terrain_tiles:
                tile_rect = box(
                    tile["xmin"] - CONFIG["tile_margin_metres"],
                    tile["ymin"] - CONFIG["tile_margin_metres"],
                    tile["xmax"] + CONFIG["tile_margin_metres"],
                    tile["ymax"] + CONFIG["tile_margin_metres"],
                )

                for segment in split_at_tile(road["geometry"], tile_rect):
                    built = make_road_mesh(
                        segment,
                        sampler,
                        settings,
                        material_id,
                        material,
                    )

                    if built is None:
                        continue

                    first = np.asarray(segment.coords[0], dtype=float)
                    origin_z = sampler.sample(float(first[0]), float(first[1]))

                    if origin_z is None:
                        xyz_source = (
                            built["surface_xyz"]
                            if len(built["surface_xyz"])
                            else built["shoulder_xyz"]
                        )
                        origin_z = float(xyz_source[0, 2])

                    origin = [float(first[0]), float(first[1]), float(origin_z)]

                    groups = []

                    if len(built["surface_xyz"]):
                        groups.append({
                            "category": ROAD_SURFACE,
                            "material_name": material_name,
                            "material_id": material_id,
                            "vertices": packed_vertices(
                                built["surface_xyz"],
                                built["surface_uv"],
                                origin,
                            ),
                        })

                    if len(built["shoulder_xyz"]):
                        groups.append({
                            "category": ROAD_SHOULDER,
                            "material_name": material_name,
                            "material_id": material_id,
                            "vertices": packed_vertices(
                                built["shoulder_xyz"],
                                built["shoulder_uv"],
                                origin,
                            ),
                        })

                    if not groups:
                        continue

                    piece_id = (
                        f"{road['id']}_{tile['name']}_"
                        f"{len(grouped[tile['name']]):03d}"
                    )

                    model = {
                        "id": piece_id,
                        "origin": origin,
                        "luokka": road["luokka"] if road["luokka"] is not None else -1,
                        "versuh": road["versuh"],
                        "groups": groups,
                    }

                    grouped[tile["name"]].append(model)

                    report.append({
                        "road_id": piece_id,
                        "source_id": road["id"],
                        "terrain_tile": tile["name"],
                        "luokka": road["luokka"],
                        "versuh": road["versuh"],
                        "surface_material": material_name,
                        "surface_width_m": settings["width"],
                        "shoulder_width_m": settings["shoulder"],
                        "status": "generated",
                    })

    tile_lookup = {tile["name"]: tile for tile in terrain_tiles}
    manifest_tiles = []

    for tile_name in sorted(grouped):
        tile = tile_lookup[tile_name]
        roads_for_tile = grouped[tile_name]

        road_filename = f"{tile_name}.road"
        write_road_file(output / "tiles" / road_filename, roads_for_tile)

        glb_file = None
        if args.glb:
            glb_file = f"glb/{tile_name}.glb"
            write_glb(
                output / glb_file,
                tile,
                roads_for_tile,
                materials,
            )

        manifest_tiles.append({
            "terrain_file": tile["terrain_file"],
            "road_file": f"tiles/{road_filename}",
            "glb_file": glb_file,
            "glb_origin_easting_northing_elevation": [
                tile["xmin"], tile["ymax"], 0.0
            ],
            "road_count": len(roads_for_tile),
            "roads": [
                {
                    "id": road["id"],
                    "origin_easting_northing_elevation": road["origin"],
                    "luokka": road["luokka"],
                    "versuh": road["versuh"],
                }
                for road in roads_for_tile
            ],
        })

    with (output / "road_index.txt").open(
        "w", encoding="utf-8", newline="\n"
    ) as handle:
        handle.write("ROAD_INDEX_V1\n")
        handle.write(f"{len(manifest_tiles)}\n")

        for tile in manifest_tiles:
            handle.write(Path(tile["terrain_file"]).name + "\n")
            handle.write(tile["road_file"] + "\n")

    (output / "road_manifest.json").write_text(
        json.dumps({
            "format": "road_manifest_v1",
            "crs": "EPSG:3067",
            "terrain_origin": terrain_origin,
            "source_roads": str(roads_path),
            "source_dem_folder": str(dem_folder),
            "source_materials": str(materials.path),
            "config": CONFIG,
            "tiles": manifest_tiles,
            "notes": [
                "Roads are draped on DEMs and split by viewer terrain tile.",
                "DEM tiles are matched to viewer terrain tiles by bounds.",
                "This first version ignores bridges and underpasses.",
                "Small class-based z offsets reduce z-fighting.",
                "Road markings are baked into combined textures.",
                "Future versions can add bridge/tunnel logic and separate markings.",
            ],
        }, indent=2),
        encoding="utf-8",
    )

    with (output / "road_report.csv").open(
        "w", encoding="utf-8", newline=""
    ) as handle:
        fieldnames = [
            "road_id",
            "source_id",
            "terrain_tile",
            "luokka",
            "versuh",
            "surface_material",
            "surface_width_m",
            "shoulder_width_m",
            "status",
        ]
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(report)

    write_format_documentation(output)

    total = sum(tile["road_count"] for tile in manifest_tiles)

    print(f"\nFinished: {total} road pieces in {len(manifest_tiles)} tiles.")
    print(f"Output: {output}")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"\nERROR: {error}", file=sys.stderr)
        sys.exit(1)
