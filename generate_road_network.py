def read_dem_manifest(folder):
    """
    Read DEM tile metadata from tile_manifest.json.

    These names do not need to match the viewer terrain names. Matching is
    done by bounds.
    """
    path = folder / "tile_manifest.json"
    manifest = json.loads(path.read_text(encoding="utf-8"))

    entries = []

    for tile in manifest["tiles"]:
        if not tile.get("dem"):
            continue

        entries.append({
            "tile": tile["tile"],
            "dem": folder / tile["dem"],
            "core_bounds": tuple(tile["core_bounds"]),
        })

    if not entries:
        raise ValueError("No DEM tiles listed in tile_manifest.json")

    return entries


def bounds_match(a, b, tolerance=1e-6):
    """Check whether two bounds tuples match."""
    return all(abs(x - y) <= tolerance for x, y in zip(a, b))


def build_dem_lookup(dem_entries, terrain_tiles):
    """
    Match DEM files to viewer terrain tiles by bounds.

    This is the key fix: viewer terrain tiles use sequential names like
    tile_000030, whereas DEM tiles may use tile_r00000_c00030.
    """
    lookup = {}

    for terrain_tile in terrain_tiles:
        matched = None

        for dem_entry in dem_entries:
            if bounds_match(dem_entry["core_bounds"], terrain_tile["bounds"]):
                matched = dem_entry
                break

        if matched is None:
            raise ValueError(
                f"No DEM tile found for terrain tile {terrain_tile['name']}"
            )

        lookup[terrain_tile["name"]] = matched

    return lookup


class DemSampler:
    """Sample elevations from original DEM tiles using viewer terrain bounds."""

    def __init__(self, dem_lookup, terrain_tiles):
        self._lookup = dem_lookup
        self._tiles = terrain_tiles
        self._datasets = {}

    def close(self):
        for dataset in self._datasets.values():
            dataset.close()
        self._datasets.clear()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        self.close()

    def tile_for_point(self, x, y):
        """Find the viewer terrain tile that contains the point."""
        for tile in self._tiles:
            if (
                tile["xmin"] <= x < tile["xmax"]
                and tile["ymin"] <= y < tile["ymax"]
            ):
                return tile

        for tile in self._tiles:
            if (
                tile["xmin"] <= x <= tile["xmax"]
                and tile["ymin"] <= y <= tile["ymax"]
            ):
                return tile

        return None

    def dataset_for_tile(self, terrain_tile_name):
        if terrain_tile_name not in self._lookup:
            raise ValueError(
                f"No DEM tile found for terrain tile {terrain_tile_name}"
            )

        if terrain_tile_name not in self._datasets:
            self._datasets[terrain_tile_name] = rasterio.open(
                self._lookup[terrain_tile_name]["dem"]
            )

        return self._datasets[terrain_tile_name]

    def sample(self, x, y):
        """Nearest-cell sample from the matched DEM tile."""
        tile = self.tile_for_point(x, y)
        if tile is None:
            return None

        dataset = self.dataset_for_tile(tile["name"])
        row, col = dataset.index(x, y)

        if (
            row < 0 or row >= dataset.height
            or col < 0 or col >= dataset.width
        ):
            return None

        value = dataset.read(1, window=Window(col, row, 1, 1))[0, 0]

        if not np.isfinite(value) or value == dataset.nodata:
            return None

        return float(value)


