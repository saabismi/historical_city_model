def read_viewer_terrain_index(folder):
    """Read viewer terrain tile layout from terrain_index.txt."""
    path = folder / "terrain_index.txt"

    with path.open("r", encoding="utf-8") as handle:
        if handle.readline().strip() != "TERRAIN_INDEX_V1":
            raise ValueError("Invalid terrain_index.txt")

        origin = [float(value) for value in handle.readline().split()]
        count = int(handle.readline().strip())

        tiles = []

        for _ in range(count):
            parts = handle.readline().split()
            if len(parts) != 7:
                raise ValueError("Invalid terrain tile record.")

            tiles.append({
                "terrain_file": parts[0],
                "name": Path(parts[0]).stem,
                "xmin": float(parts[1]),
                "ymin": float(parts[2]),
                "xmax": float(parts[3]),
                "ymax": float(parts[4]),
                "zmin": float(parts[5]),
                "zmax": float(parts[6]),
                "bounds": (
                    float(parts[1]),
                    float(parts[2]),
                    float(parts[3]),
                    float(parts[4]),
                ),
            })

    return origin, tiles


