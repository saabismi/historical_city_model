def load_texture_image(path):
    with Image.open(path) as image:
        return image.convert("RGBA").copy()


class RoadMaterials:
    """Shared texture/material definitions used by all road tiles."""

    def __init__(self, path):
        self.path = Path(path).resolve()
        self.root = self.path.parent
        self.config = json.loads(self.path.read_text(encoding="utf-8"))
        self.table = self.config["materials"]
        self.ids = {
            name: index
            for index, name in enumerate(sorted(self.table))
        }
        self.images = {}

        default_surface = self.config["default"]["surface"]
        if default_surface not in self.table:
            raise ValueError(f"Unknown default surface material: {default_surface}")

        for name, material in self.table.items():
            texture = self.root / material["texture"]
            viewer_texture = self.root / material["viewer_texture"]

            if not texture.is_file():
                raise ValueError(f"Missing texture: {texture}")
            if not viewer_texture.is_file():
                raise ValueError(f"Missing viewer texture: {viewer_texture}")

            for key in ("repeat_length_metres", "repeat_width_metres"):
                if float(material.get(key, 0)) <= 0:
                    raise ValueError(f"{name}: invalid {key}")

    def choose_for_class(self, luokka):
        classes = self.config.get("class_assignments", {})
        fallback = classes.get("fallback", {})
        entry = classes.get(str(luokka), fallback)

        if not entry:
            return self.config["default"]["surface"]

        name = entry["surface_material"]
        if name not in self.table:
            raise ValueError(
                f"Road class {luokka}: unknown surface material {name}"
            )

        return name

    def image(self, name):
        if name not in self.images:
            self.images[name] = load_texture_image(
                self.root / self.table[name]["texture"]
            )
        return self.images[name]

    def export(self, output):
        """Copy textures and write a runtime material index."""
        texture_dir = output / "textures"
        texture_dir.mkdir(exist_ok=True)

        with (output / "road_materials.txt").open(
            "w", encoding="utf-8", newline="\n"
        ) as handle:
            handle.write(f"ROAD_MATERIALS_V1\n{len(self.ids)}\n")

            for name, identifier in self.ids.items():
                relative = f"textures/material_{identifier:04d}.tga"
                shutil.copy2(
                    self.root / self.table[name]["viewer_texture"],
                    output / relative,
                )
                handle.write(f"{identifier}\n{name}\n{relative}\n")

        exported = json.loads(json.dumps(self.config))

        for name, material in exported["materials"].items():
            identifier = self.ids[name]
            png_relative = f"textures/material_{identifier:04d}.png"
            shutil.copy2(self.root / material["texture"], output / png_relative)
            material["texture"] = png_relative
            material["viewer_texture"] = f"textures/material_{identifier:04d}.tga"

        (output / "road_materials.json").write_text(
            json.dumps(exported, indent=2), encoding="utf-8"
        )


