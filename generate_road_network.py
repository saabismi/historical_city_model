def normalized_srs(crs):
    result = crs.Clone()
    result.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER)
    return result


def read_roads(filename, layer_name):
    """Read tieviiva features with LUOKKA and VERSUH."""
    ogr.UseExceptions()
    osr.UseExceptions()

    dataset = ogr.Open(str(filename))
    if dataset is None:
        raise ValueError(f"Cannot open roads GeoPackage: {filename}")

    layer = dataset.GetLayerByName(layer_name)
    if layer is None:
        raise ValueError(f"Road layer not found: {layer_name}")

    source_crs = layer.GetSpatialRef()
    if source_crs is None:
        raise ValueError("Road layer has no CRS.")

    expected = osr.SpatialReference()
    expected.ImportFromEPSG(3067)
    expected.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER)

    source_crs = normalized_srs(source_crs)
    transformation = None

    if not source_crs.IsSame(expected):
        print("Reprojecting roads to EPSG:3067.")
        transformation = osr.CoordinateTransformation(source_crs, expected)

    definition = layer.GetLayerDefn()

    if definition.GetFieldIndex("LUOKKA") < 0:
        raise ValueError("Road layer has no LUOKKA field.")

    if definition.GetFieldIndex("VERSUH") < 0:
        print("WARNING: Road layer has no VERSUH field; assuming 0.")

    roads = []
    counter = 0

    for feature in layer:
        geometry = feature.GetGeometryRef()
        if geometry is None or geometry.IsEmpty():
            continue

        geometry = geometry.Clone()

        if transformation is not None:
            if geometry.Transform(transformation) != 0:
                raise RuntimeError("Road geometry transformation failed.")

        shape = from_wkb(bytes(geometry.ExportToWkb()))
        if shape.is_empty:
            continue

        luokka = feature.GetField("LUOKKA")
        versuh = feature.GetField("VERSUH")

        try:
            luokka = int(luokka)
        except (TypeError, ValueError):
            luokka = None

        try:
            versuh = int(versuh)
        except (TypeError, ValueError):
            versuh = 0

        lines = []
        if isinstance(shape, LineString):
            lines = [shape]
        elif isinstance(shape, MultiLineString):
            lines = [part for part in shape.geoms if part.length > 0]

        for line in lines:
            if line.is_empty or line.length <= 0:
                continue

            counter += 1
            roads.append({
                "id": f"road_{counter:06d}",
                "geometry": line,
                "luokka": luokka,
                "versuh": versuh,
            })

    dataset = None

    if not roads:
        raise ValueError("No usable road line features found.")

    return roads


